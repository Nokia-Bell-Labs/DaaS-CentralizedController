"""Write the RAS shaper files that the controller used to send to a remote host.

Each ingress profile becomes a pair of files in one local directory:

    {endpoint}-TM.cfg
    {endpoint}-STREAMS.cfg
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional

from pydantic import BaseModel, Field


class FlowProfile(BaseModel):
    """Per-flow fields needed to render STREAMS.cfg and TM.cfg."""
    df_id: str
    sr_Mbps: int
    path_link_ids: List[str]
    src_ip: Optional[str] = None
    dst_ip: Optional[str] = None
    latency_ns: Optional[int] = None
    l_max_bytes: Optional[int] = None
    vlan_id: Optional[str] = None
    vlan_pri: Optional[int] = None
    path_number: Optional[int] = None


class IngressProfile(BaseModel):
    """Bundle-aware PSS profile for one ingress link."""
    ingress_link_id: str
    slot_duration_s: float
    period_slots: int
    link_capacity_Mbps: Optional[int] = None
    bytes_per_slot: int
    slots: List[str]
    bundle_members: Dict[str, List[str]]
    bundle_id_by_flow: Dict[str, str]
    bundle_effective_rates: Dict[str, int] = Field(default_factory=dict)
    flows: List[FlowProfile]


def endpoint_name_for_ingress(ingress_link_id: str) -> str:
    """'u01l01_l01' -> 'u01l01'. The link id is the endpoint id plus '_' plus the leaf port."""
    parts = ingress_link_id.split("_")
    if len(parts) >= 2:
        return "_".join(parts[:-1])
    return parts[0] if parts else ingress_link_id


def render_streams_cfg(profile: IngressProfile, endpoint_name: str) -> str:
    now = datetime.now()
    lines = [
        "############################################################",
        "# TG10 Stream Configuration File",
        f"# Copyright: Nokia, {now.year}",
        "#",
        "# Comment line must begin with '#' in column1.",
        "# The field delimiter is a <tab>.",
        "#",
        "[CONFIG_DESCRIPTION]",
        f"Name\t{endpoint_name}-STREAMS.cfg",
        f"Description\tTG10 stream configuration file for endpoint {endpoint_name}",
        "Author\tAuto-generated by DaaS Centralized Controller",
        f"Date\t{now.strftime('%a %b %d %H:%M:%S %Y')}",
        "[CONFIG_STREAMS]",
        "#id\tsrcIP\t\tdstIP\t\trate (Mb/s)\tlatency\tpktsize\tvlanId\tvlanPri",
    ]
    for idx, flow in enumerate(profile.flows, start=1):
        src_ip = flow.src_ip or "0.0.0.0"
        dst_ip = flow.dst_ip or "0.0.0.0"
        rate = float(flow.sr_Mbps)
        latency_ns = flow.latency_ns or 1000000000
        latency_us = latency_ns / 1e3
        pktsize = (flow.l_max_bytes - 70) if flow.l_max_bytes else 1472
        vlan_id = flow.vlan_id
        if vlan_id is None:
            default_id = int(flow.df_id) if flow.df_id.isdigit() else 100 + idx
            vlan_id = hex(default_id)
        vlan_pri = 7 if flow.vlan_pri is None else flow.vlan_pri
        lines.append(
            f"{idx}\t{src_ip}\t{dst_ip}\t{rate:.3f}\t{latency_us:.3f}\t{pktsize}\t{vlan_id}\t{vlan_pri}"
        )
    return "\n".join(lines) + "\n"


def render_tm_cfg(profile: IngressProfile, endpoint_name: str) -> str:
    now = datetime.now()
    lines = [
        "############################################################",
        "# TG10/TM10 Configuration File",
        f"# Copyright: Nokia, {now.year}",
        "#",
        "# This file is broken up into sections identified by [<section_name>].",
        "# The sections listed in this file are scheduling type dependent.  Those included",
        "# must be consistently defined for inter-dependencies (e.g. # of queues and bundles).",
        "# This file may be hand-created or automatically generated, e.g. using DaaS-CC.",
        "#",
        "# Comment line must begin with '#' in column1.",
        "# The field delimiter is a <tab>.",
        "#",
        "[CONFIG_DESCRIPTION]",
        f"Name\t{endpoint_name}-TM.cfg",
        f"Description\tTG10/TM10 PSS configuration file for endpoint {endpoint_name}",
        "Author\tAuto-generated by DaaS-CC",
        f"Date\t{now.strftime('%a %b %d %H:%M:%S %Y')}",
        "[CONFIG_TOPLVL]",
        "# Scheduler top level configurations: only 1 entry is allowed.",
        "# This section must be defined before other sections of scheduler parameters.",
        "# Columns: 1=algorithm [DCB_Q, XBS, RR (for testing only)]",
        "#          2=number of queues",
        "#          3=number of timeslots",
        "#          4=max packet size",
        "#          5=base flow/stream id for this host",
        "#          6=packet classification method [1: VLANID and SRCMAC, 2: VLANID or TTL, 3: SRCPORT]",
        "#          7=ECN threshold [ms]",
    ]
    num_queues = len(profile.flows) + 1
    lines.append(
        f"DCB_Q\t{num_queues}\t{profile.period_slots}\t{profile.bytes_per_slot}\t1\t3\t5.0"
    )
    lines.append("[GBS_TIMESLOT_QUEUE_MAP]")
    lines.append("# Each row is configuration for a GBS timeslot.")
    lines.append("# Columns: 1=timeslot id, 2=bundle id")

    bundle_to_queue_id: Dict[str, int] = {"empty": 0}
    queue_counter = 1
    for bundle_id in profile.bundle_members:
        if bundle_id not in bundle_to_queue_id:
            bundle_to_queue_id[bundle_id] = queue_counter
            queue_counter += 1

    for slot_idx, bundle_id in enumerate(profile.slots):
        lines.append(f"{slot_idx}\t{bundle_to_queue_id.get(bundle_id, 0)}")

    lines.append("[GBS_SCHEDULING_RATE]")
    lines.append("# Each row specifies scheduling rate of a GBS queue/bundle")
    lines.append("# Columns: 1=queue/bundle id, 2=rate, 3=path number")

    for bundle_id, flow_ids in profile.bundle_members.items():
        queue_id = bundle_to_queue_id.get(bundle_id, 0)
        if queue_id == 0:
            continue
        effective_rates = profile.bundle_effective_rates
        if bundle_id in effective_rates:
            rate = float(effective_rates[bundle_id])
            flow = next((f for f in profile.flows if f.df_id == flow_ids[0]), None) if flow_ids else None
        elif flow_ids:
            flow = next((f for f in profile.flows if f.df_id == flow_ids[0]), None)
            rate = float(flow.sr_Mbps) if flow else 0.0
        else:
            flow = None
            rate = 0.0
        if flow is None:
            continue
        path_number = flow.path_number
        if path_number is None:
            path_number = int(flow.df_id) if flow.df_id.isdigit() else queue_id
        lines.append(f"{queue_id}\t{rate:.3f}\t{path_number}")

    lines.append("[GBS_BUNDLE_MAPPING]")
    lines.append("# Each row specifies queue-to-bundle mapping, if applicable.  If a bundle contains more than one queue,")
    lines.append("# a separate line is listed for each queue.")
    lines.append("# Columns: 1=bundle id, 2=queue id")
    for bundle_id, flow_ids in profile.bundle_members.items():
        bundle_queue_id = bundle_to_queue_id.get(bundle_id, 0)
        if bundle_queue_id == 0:
            continue
        for flow_id_str in flow_ids:
            flow_idx = next((i for i, f in enumerate(profile.flows, start=1) if f.df_id == flow_id_str), None)
            if flow_idx:
                lines.append(f"{bundle_queue_id}\t{flow_idx}")

    return "\n".join(lines) + "\n"


def write_endpoint_configs(output_dir: Path, profile: IngressProfile) -> Dict[str, str]:
    """Write the current TM and STREAMS files for this profile's endpoint. Returns the two paths."""
    output_dir.mkdir(parents=True, exist_ok=True)
    endpoint_name = endpoint_name_for_ingress(profile.ingress_link_id)
    streams_path = output_dir / f"{endpoint_name}-STREAMS.cfg"
    tm_path = output_dir / f"{endpoint_name}-TM.cfg"
    streams_path.write_text(render_streams_cfg(profile, endpoint_name), encoding="utf-8")
    tm_path.write_text(render_tm_cfg(profile, endpoint_name), encoding="utf-8")
    return {"streams_cfg": str(streams_path), "tm_cfg": str(tm_path)}
